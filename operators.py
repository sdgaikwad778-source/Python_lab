#Arithemtic opeateros
a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
#// → division without the decimal part
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

#Comparison Operator
a = 10
b = 5

print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

#Assignemt Operator

x = 10

print("Initial value:", x)

x += 5
print("After +=:", x)

x -= 3
print("After -=:", x)

x *= 2
print("After *=:", x)

x /= 4
print("After /=:", x)

#Logical Operators

age = 20

print(age >= 18 and age <= 25)
print(age < 18 or age > 25)
print(not age < 18)